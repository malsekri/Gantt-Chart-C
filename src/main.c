#include <stdio.h>
#include "functions.h"

int main() {

    /*
     * Variable Declarations
     */
    GanttChart chart = {0}; // Stores the current chart data

    //Print welcome message and input user choice for example gantt chart or new chart.
    printf("Welcome to the Gantt Generator!"
           "\n0: New Chart"
           "\n1: Example Chart"
           "\nPlease enter selection: ");
    fflush(stdout);

    int input = 0, editing = -1;
    scanf("%d", &input);

    switch(input) {
        /* Creates a new chart from user input */
        case 0:
            chart = createChart();
            while(editing != 0) { // Reprints chart after every edit made
                printGantt(chart);
                ActionResponse response = chartAction(chart);
                chart = response.chart;
                editing = response.code;
            }
            break;

        /* Uses pre-existing chart data */
        case 1:
            chart = getExample();
            while(editing != 0) {
                printGantt(chart);
                ActionResponse response = chartAction(chart);
                chart = response.chart;
                editing = response.code;
            }
            break;

        default:
            printf("Invalid input! Please enter a number between 0-1!");
            fflush(stdout);
            break;
    }

    return 0;
}

